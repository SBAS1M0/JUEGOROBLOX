Templates.ById = {}
for index, template in ipairs(Templates.List) do
	template.index = index
	template.flat = table.concat(template.rows)
	Templates.ById[template.id] = template
end

function Templates.get(id)
	return Templates.ById[id]
end

-- Devuelve las plantillas desbloqueadas para un nivel dado.
function Templates.unlockedFor(level)
	local result = {}
	for _, template in ipairs(Templates.List) do
		if template.level <= level then
			table.insert(result, template)
		end
	end
	return result
end

-- Siguiente plantilla que se desbloqueará (o nil si ya están todas).
function Templates.nextUnlock(level)
	for _, template in ipairs(Templates.List) do
		if template.level > level then
			return template
		end
	end
	return nil
end

return Templates
